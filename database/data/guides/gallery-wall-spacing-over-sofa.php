<h2 id="paper-templates">Plan it with paper templates</h2>
<p>Paper templates let you test the whole layout before a single hole goes in the wall.</p>
<ul>
<li><strong>Step 1, cut templates:</strong> trace each frame onto brown paper or newspaper and cut it out. Write the frame size on each one.</li>
<li><strong>Step 2, mark the hanging point:</strong> on the back of each frame, pull the wire taut towards the top (or find the D-ring or sawtooth hanger) and measure down from the top edge. Mark that point on the template.</li>
<li><strong>Step 3, lay it out on the floor:</strong> arrange the templates on the floor in front of the sofa first, using your card spacer for the gaps.</li>
<li><strong>Step 4, tape it to the wall:</strong> use low-tack painter&rsquo;s tape. Mark the bottom-edge line lightly in pencil and use a spirit level to keep rows straight.</li>
<li><strong>Step 5, live with it:</strong> leave the templates up for a day. Sit on the sofa, walk past, and see how it looks from the doorway.</li>
<li><strong>Step 6, fix through the template:</strong> put the hook or nail through each marked hanging point, then tear the paper away and hang the frame.</li>
</ul>
<p>The hanging height of each fixing is: <strong>bottom of frame height + frame height &minus; drop from the top of the frame to the hanging point</strong>. For a 40 cm tall frame whose taut wire sits 6 cm below the top, hung with its bottom edge at 103 cm, the fixing goes at 103 + 40 &minus; 6 = 137 cm.</p>

<blockquote><p><strong>Tip:</strong> Hang the anchor or the centre column first, then work outwards using the card spacer. Small errors stay small when they start from the middle; started from one end, they add up across the whole wall.</p></blockquote>

<h2 id="fixings-and-safety">Fixings and safety</h2>
<ul>
<li><strong>Check for pipes and cables:</strong> use a detector before drilling, particularly directly above or below sockets and switches.</li>
<li><strong>Match the fixing to the wall:</strong> plasterboard, plaster on brick and timber panelling all need different fixings. Check the weight rating on the packaging and allow a margin for heavier glazed frames.</li>
<li><strong>Glass over a sofa:</strong> for large frames, consider acrylic glazing instead of glass, and use two fixings per frame so it stays level.</li>
<li><strong>Renting:</strong> check your tenancy agreement and ask your landlord in writing before drilling. Removable adhesive strips can work for light frames, but test them on a hidden spot first, as they can lift paint and affect your deposit.</li>
</ul>

<h2 id="common-mistakes">Common mistakes to avoid</h2>
<ul>
<li><strong>Hanging too high.</strong> The most common error. Keep the bottom edge 20&ndash;25 cm above the sofa back.</li>
<li><strong>Too narrow.</strong> A group under about 60% of the sofa width looks undersized.</li>
<li><strong>Uneven gaps.</strong> Consistent spacing matters more than which spacing you choose.</li>
<li><strong>Ignoring the room.</strong> Line the arrangement up with the sofa, not the wall, unless the sofa itself is centred on the wall.</li>
</ul>

