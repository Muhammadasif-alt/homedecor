<p>A gallery wall above a sofa is one of the most satisfying ways to fill a large living room wall, and one of the easiest to get slightly wrong. Hung too high, the frames float away from the furniture. Spaced too widely, they read as a scatter of separate pictures rather than one composition. The fix is a handful of measurements. This guide walks through gallery wall spacing over a sofa using a common size, an 84 in sofa (213 cm), with formulas you can apply to any sofa and two fully worked layouts.</p>

<h2 id="the-four-numbers">The four numbers that matter</h2>
<ul>
<li><strong>Overall width:</strong> about two-thirds of the sofa width. For a 213 cm (84 in) sofa that is around 140&ndash;160 cm (55&ndash;63 in).</li>
<li><strong>Height above the sofa:</strong> the bottom edge of the arrangement 20&ndash;25 cm (8&ndash;10 in) above the top of the sofa back.</li>
<li><strong>Gaps between frames:</strong> 5&ndash;8 cm (2&ndash;3 in), kept consistent.</li>
<li><strong>Centre height:</strong> the visual centre of the whole group roughly 145&ndash;152 cm (57&ndash;60 in) from the floor, the same eye-level rule galleries use for single pictures.</li>
</ul>
<p>Over a sofa, the &ldquo;height above the sofa&rdquo; rule takes priority, because the frames need to relate to the furniture. Use the centre-height rule as a check: if your arrangement&rsquo;s centre lands well outside 145&ndash;152 cm, adjust its overall height rather than lifting the whole thing away from the sofa.</p>

<h2 id="overall-width">Working out the overall width</h2>
<p>The formula is simple: <strong>sofa width × 0.66 to 0.75</strong>.</p>
<ul>
<li>213 cm × 0.66 = about 141 cm (55 in).</li>
<li>213 cm × 0.75 = about 160 cm (63 in).</li>
</ul>
<p>Narrower than about 60% and the art looks lost above a long sofa. Wider than the sofa itself and the wall starts to feel crowded, unless you are deliberately running the arrangement across the whole wall. Measure the sofa from arm to arm at its widest point, not just the seat.</p>

<h2 id="height-above-the-sofa">Getting the height right</h2>
<p>Measure the height of the sofa back from the floor. Most sofas sit somewhere around 75&ndash;90 cm (30&ndash;35 in). Then:</p>
<ul>
<li><strong>Bottom edge of the arrangement</strong> = sofa back height + 20&ndash;25 cm.</li>
<li><strong>Centre of the arrangement</strong> = bottom edge + half the arrangement&rsquo;s height.</li>
</ul>
<p>Leave at least 20 cm so heads do not knock the frames when people lean back, and so cushions can be plumped without catching glass. More than about 30 cm and the art begins to disconnect from the sofa.</p>

<h2 id="spacing-between-frames">Spacing between frames</h2>
<p>Consistent gaps are what make a gallery wall look designed rather than accidental.</p>
<ul>
<li><strong>5 cm (2 in):</strong> tight and modern; suits small frames and grid layouts.</li>
<li><strong>6&ndash;7 cm (about 2.5 in):</strong> the comfortable middle and the easiest to live with.</li>
<li><strong>8 cm (3 in):</strong> more breathing room; suits larger frames or thick mounts.</li>
</ul>
<p>Go much beyond 8 cm and frames start to separate visually. Whatever you choose, cut a spacer from card to that exact width and use it between every pair of frames as you hang.</p>

<h2 id="grid-or-salon">Grid or salon layout?</h2>
<h3>Grid layouts</h3>
<p>Identical frames in neat rows and columns with equal gaps. A grid feels calm, architectural and tailored, and suits modern and minimal rooms. It is also the easiest to plan, because the maths is exact. Grids are unforgiving of mistakes, though: a 1 cm error is obvious.</p>
<h3>Salon layouts</h3>
<p>A mix of sizes, orientations and often frame finishes, arranged inside an imaginary rectangle. Salon walls feel collected and relaxed and can grow over time. The trick is to keep the outer edges roughly aligned and the gaps consistent, so the variety reads as one group. Start with the largest piece, the anchor, slightly off centre, and build outwards.</p>

<h2 id="worked-example-grid">Worked example 1: a grid over an 84 in sofa</h2>
<p>Sofa: 213 cm (84 in) wide, sofa back 80 cm (31.5 in) high. Eight identical portrait frames, each 30 × 40 cm (about 12 × 16 in), in two rows of four, with 8 cm (3 in) gaps.</p>
<ul>
<li><strong>Overall width:</strong> (4 × 30) + (3 × 8) = 120 + 24 = <strong>144 cm (57 in)</strong>, which is 68% of the sofa width.</li>
<li><strong>Overall height:</strong> (2 × 40) + 8 = <strong>88 cm (35 in)</strong>.</li>
<li><strong>Bottom edge:</strong> 80 + 23 = <strong>103 cm</strong> from the floor.</li>
<li><strong>Top edge:</strong> 103 + 88 = <strong>191 cm</strong>.</li>
<li><strong>Centre:</strong> 103 + 44 = <strong>147 cm (58 in)</strong>, inside the 145&ndash;152 cm eye-level range.</li>
<li><strong>Horizontal position:</strong> centre the grid on the sofa, so each outer edge sits (213 &minus; 144) ÷ 2 = about 35 cm in from the sofa arms.</li>
</ul>

<h2 id="worked-example-salon">Worked example 2: a salon wall over the same sofa</h2>
<p>Same sofa, five frames of mixed sizes, with 6 cm (about 2.5 in) gaps:</p>
<ul>
<li>One anchor print, 60 × 80 cm (about 24 × 32 in), portrait, in the middle column.</li>
<li>Two 40 × 50 cm (about 16 × 20 in) frames.</li>
<li>Two 30 × 40 cm (about 12 × 16 in) frames.</li>
</ul>
<p>Arrange them in three columns: on the left, a 40 × 50 cm frame above a 30 × 40 cm frame; the anchor in the centre; on the right, a 30 × 40 cm frame above a 40 × 50 cm frame. Mirroring the two side columns keeps the group balanced without being rigidly symmetrical.</p>
<ul>
<li><strong>Overall width:</strong> 40 + 6 + 60 + 6 + 40 = <strong>152 cm (60 in)</strong>, which is 71% of the sofa width.</li>
<li><strong>Overall height:</strong> each side column is 50 + 6 + 40 = <strong>96 cm (38 in)</strong>; the 80 cm anchor is centred vertically within it, leaving 8 cm above and below.</li>
<li><strong>Bottom edge:</strong> 80 + 23 = <strong>103 cm</strong>.</li>
<li><strong>Centre:</strong> 103 + 48 = <strong>151 cm (59.5 in)</strong>, still inside the eye-level range.</li>
<li><strong>Top edge:</strong> 103 + 96 = <strong>199 cm</strong>. With a typical 240 cm ceiling, that leaves about 40 cm of clear wall above.</li>
</ul>
<p>If your sofa is lower, say a 70 cm back, keep the 20&ndash;25 cm gap and accept a slightly lower centre. The relationship to the sofa matters more than hitting the eye-level number exactly.</p>

