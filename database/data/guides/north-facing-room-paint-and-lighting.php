<h2 id="mirrors">Use mirrors to bounce light</h2>
<p>Mirrors are one of the most effective ways to make the most of limited daylight.</p>
<ul>
<li>Place a large mirror on a wall adjacent to the window, or opposite it, so it catches the daylight and throws it deeper into the room.</li>
<li>Mirrors positioned behind lamps double the glow in the evening.</li>
<li>A cluster of smaller mirrors works well in a hallway or on a dark wall.</li>
<li>Glossy surfaces such as glass tables, lacquered furniture and polished tiles add to the effect.</li>
</ul>
<p>Fix heavy mirrors securely with fixings suitable for the wall and the mirror's weight.</p>

<h2 id="artificial-lighting">Artificial lighting for a north-facing room</h2>
<p>Because daylight is limited, especially in winter, the right bulbs are just as important as the paint.</p>
<ul>
<li><strong>Use warm-white bulbs:</strong> 2700–3000K counteracts the cool daylight. Avoid cool white and "daylight" bulbs in living spaces and bedrooms, as they reinforce the cold feel.</li>
<li><strong>Layer your light:</strong> combine overhead lights with floor lamps, table lamps and wall lights so the room is lit from several points and heights.</li>
<li><strong>Light the corners:</strong> dark corners make a room feel smaller and gloomier. A floor lamp or uplighter in each dim corner makes a real difference.</li>
<li><strong>Turn lamps on early:</strong> on dark winter days, switch on a couple of lamps in the afternoon rather than waiting for night. Smart plugs or timers make this easy.</li>
<li><strong>Test paint under your bulbs:</strong> a colour you love in daylight can shift under artificial light, so check your swatches in the evening too.</li>
</ul>
<p>For a room-by-room approach, see our <a href="/blog/layered-lighting-room-by-room-guide">layered lighting guide</a>.</p>

<h2 id="window-and-soft-furnishings">Window treatments and soft furnishings</h2>
<ul>
<li><strong>Do not block the light.</strong> Choose curtain poles that extend beyond the window frame so curtains stack clear of the glass when open.</li>
<li><strong>Use light, warm fabrics.</strong> Sheer linen in warm white or oatmeal softens the room without losing daylight.</li>
<li><strong>Bring warmth with textiles:</strong> rugs, cushions and throws in warm colours such as rust, mustard and camel, and natural textures such as wool, jute and boucle, help a cool room feel inviting.</li>
<li><strong>Wood tones:</strong> warm timber furniture and floors add natural warmth that cool light cannot take away.</li>
</ul>

<h2 id="quick-checklist">Quick checklist</h2>
<ul>
<li>Warm-undertone whites, never cool brilliant white.</li>
<li>Consider deeper, warm colours that embrace the soft light.</li>
<li>Avoid cool greys, grey-blues and icy pastels.</li>
<li>Test large swatches on several walls at different times.</li>
<li>Warm-white 2700–3000K bulbs and layered lighting.</li>
<li>Mirrors and reflective finishes to bounce light.</li>
<li>Warm textiles and wood to finish.</li>
</ul>

