<p>North-facing rooms have a reputation for being dull and chilly, and paint is often blamed. In truth, the light in a north-facing room is not worse, just different. It is cool, soft and remarkably consistent through the day, which is why artists have long preferred north light for studios. The challenge is that this light changes how colours look, and the "safe" brilliant white or pale grey that works elsewhere can turn flat and cold here.</p>
<p>This guide explains how north light behaves, which paint colours work with it rather than against it, and how to use artificial lighting, mirrors and finishes so the room feels warm and welcoming at any time of day.</p>
<p>A quick note on geography: this guide is written for the northern hemisphere, including the UK. South of the equator it reverses, so it is a south-facing room that gets this cool, indirect light.</p>

<h2 id="how-north-light-behaves">How north light behaves</h2>
<p>In the northern hemisphere, a north-facing window rarely receives direct sunlight. Instead, the room is lit by indirect light from the sky, which has a cooler, slightly bluish cast. It also tends to be lower in intensity than the light in a south-facing room.</p>
<ul>
<li><strong>Cool:</strong> the blue cast pushes colours towards grey and blue. Warm colours look more muted; cool colours look colder.</li>
<li><strong>Consistent:</strong> the light changes far less between morning and evening than in east- or west-facing rooms. A colour that works at ten in the morning will look similar at four in the afternoon, which makes choosing easier once you understand it.</li>
<li><strong>Soft:</strong> there are few hard shadows or bright patches. That suits textured finishes and rich colours, which look velvety rather than harsh.</li>
<li><strong>Weaker in winter:</strong> in the darker months, artificial light does much of the work, even in the daytime. Plan the lighting as carefully as the paint.</li>
</ul>

<h2 id="choosing-whites">Choosing a white that will not look grey</h2>
<p>Brilliant white is the most common mistake in north-facing rooms. Without warm sunlight to brighten it, it takes on the blue cast of the sky and reads as grey or slightly dingy. The answer is a white with a warm undertone.</p>
<ul>
<li><strong>Look for yellow, red or pink undertones.</strong> Creamy whites, soft ivories, warm off-whites and whites with a hint of pink all balance the cool light. In a north room they tend to look like a clean, soft white rather than cream.</li>
<li><strong>Avoid grey-blue or green-based whites.</strong> Cool, crisp whites with a blue or grey base will exaggerate the coolness of the room.</li>
<li><strong>Compare whites side by side.</strong> Undertones are hard to see on their own. Hold several white swatches against a sheet of plain printer paper; the undertone becomes obvious.</li>
<li><strong>Do not go too yellow.</strong> A strongly yellow cream can look muddy in low light. Look for warmth that is subtle.</li>
</ul>

<h2 id="embrace-deeper-colours">Embrace it with deeper colours</h2>
<p>You will never make a north-facing room as bright as a south-facing one with paint alone, so one of the most successful approaches is to stop trying. Rich, deeper colours look wonderful in soft north light, creating an enveloping, cosy room rather than a pale one that feels a little sad.</p>
<ul>
<li><strong>Earthy warm tones:</strong> terracotta, ochre, warm clay and rust feel naturally warm and glow under evening lamps.</li>
<li><strong>Deep greens:</strong> olive, moss and green with yellow undertones work better than cool, blue-based greens.</li>
<li><strong>Warm neutrals:</strong> mushroom, taupe, stone and greige with a warm base give a calm backdrop without the coldness of a true grey.</li>
<li><strong>Dark, moody colours:</strong> inky blues, aubergine and chocolate can work beautifully in a north-facing bedroom, snug or dining room. Choose versions with a red or warm base and commit fully, including woodwork and even the ceiling, for a cocooning effect.</li>
</ul>
<p>What to avoid: cool greys, icy pastels and grey-blues. These are the colours most likely to make a north-facing room feel chilly. If you love grey, pick one with a warm, brown or red base rather than a blue or green one.</p>

<h2 id="test-swatches">How to test paint properly</h2>
<p>A tiny tester square tells you very little. In a north-facing room, testing is the step that makes the biggest difference.</p>
<ul>
<li><strong>Go large.</strong> Paint swatches of at least A3 size, around 30 × 42 cm (12 × 16.5 in), or use peel-and-stick sample sheets or painted lining paper. Bigger is better.</li>
<li><strong>Use two coats.</strong> One coat will not show the true colour.</li>
<li><strong>Test on more than one wall,</strong> including the wall with the window and the darkest corner. The same paint will look different on each.</li>
<li><strong>Look at different times:</strong> morning, midday, late afternoon and in the evening under your own lamps. Look on a grey day as well as a bright one.</li>
<li><strong>Isolate the swatch.</strong> Surround the sample with white paper or paint it on a board so the existing wall colour does not influence your eye.</li>
<li><strong>Live with it for a few days</strong> before deciding.</li>
</ul>
<blockquote><p><strong>Tip:</strong> Paint the sample boards, not the wall. You can then move them around the room, hold them next to the sofa, curtains and floor, and take them to the window, which is far more useful than a fixed patch.</p></blockquote>

<h2 id="finishes">Light-reflective finishes</h2>
<ul>
<li><strong>Eggshell or satin on walls</strong> reflects a little more light than flat matt. Bear in mind that more sheen also shows up imperfections on uneven walls.</li>
<li><strong>Ceilings:</strong> a warm white ceiling, a touch lighter than the walls, bounces light back down. A pale tint of the wall colour also works well.</li>
<li><strong>Woodwork:</strong> skirting, doors and frames in a satin or gloss finish catch the light and add crispness.</li>
<li><strong>Light-reflective paints:</strong> some ranges are formulated to bounce more light. They can help, but check manufacturer information and test them like any other colour.</li>
<li><strong>Metallic accents:</strong> brass, gold and copper accessories reflect warm light. A little goes a long way.</li>
</ul>

