<h2 id="coffee-table-check">The coffee table check</h2>
<p>Whatever size you choose, run one last check on the coffee table:</p>
<ul>
<li>Leave about 40&ndash;45 cm (16&ndash;18 in) between the front of the seats and the coffee table, close enough to reach a cup, far enough to walk past.</li>
<li>The coffee table should sit fully on the rug, with ideally at least 45 cm (18 in) of rug beyond it on the open side.</li>
<li>If the table hangs off the rug edge, the rug is too small, or it needs turning through 90 degrees.</li>
</ul>

<h2 id="tape-outline-method">Measure it on the floor: the tape-outline method</h2>
<p>Numbers on paper are useful, but nothing beats seeing the shape on your own floor. This takes about 15 minutes.</p>
<ul>
<li><strong>Step 1, measure the room:</strong> wall to wall in both directions at floor level, and note any doors that swing into the room.</li>
<li><strong>Step 2, measure the sectional:</strong> long arm, short arm and seat depth.</li>
<li><strong>Step 3, mark the tuck line.</strong> Using low-tack masking tape, run a line on the floor about 15&ndash;20 cm in from the front edge of the seats along both arms. This is where the rug edge will sit.</li>
<li><strong>Step 4, tape the full rectangle</strong> for the size you are considering, starting from that corner. Use a tape measure and check the diagonals are equal so the rectangle is square.</li>
<li><strong>Step 5, check the borders:</strong> measure from each taped edge to the wall and aim for 30&ndash;45 cm.</li>
<li><strong>Step 6, check the door:</strong> make sure no door has to drag over the rug. If one does, allow for the rug and pad height, or choose a smaller size or a thinner pad.</li>
<li><strong>Step 7, live with it for a day.</strong> Walk the routes you normally use and move the coffee table into place. If the tape annoys you, the rug will too.</li>
</ul>
<p>Test the tape on a hidden spot first, especially on oiled or freshly finished wooden floors, and remove it the same day.</p>

<blockquote><p><strong>Tip:</strong> If you are torn between two sizes in a 12 × 14 room, go for the larger one as long as it still leaves 30 cm of floor to the walls. An undersized rug is a far more common mistake than an oversized one.</p></blockquote>

<h2 id="common-mistakes">Common mistakes to avoid</h2>
<ul>
<li><strong>Centring the rug on the room instead of the seating.</strong> With a sectional, the rug belongs to the sofa, so line it up with the L, not with the middle of the floor.</li>
<li><strong>Only one arm on the rug.</strong> If the front legs of one arm are on and the other arm floats off, the zone looks lopsided.</li>
<li><strong>Forgetting the rug pad.</strong> A pad stops the rug creeping out from under the sofa and protects the floor. Cut it about 2.5 cm (1 in) smaller than the rug on each side.</li>
<li><strong>Ignoring circulation.</strong> Keep a clear walkway of about 75&ndash;90 cm (30&ndash;36 in) where people cross the room, ideally on the rug or fully off it, not along its edge.</li>
</ul>

