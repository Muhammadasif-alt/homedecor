<p>A 12 × 14 ft living room is about 3.7 × 4.3 m, or more precisely 366 × 427 cm. It is a very common size, and it is exactly the size where an L-shaped sofa and the wrong rug start to fight. Too small and the rug floats in front of the sofa like a doormat; too large and it creeps up the skirting and makes the room feel cramped. The good news is that choosing a rug size for a sectional is mostly simple maths. This guide gives you the rules, the formulas and three worked examples, all based on a 12 × 14 room.</p>

<h2 id="the-short-answer">The short answer</h2>
<p>For most 12 × 14 living rooms with a sectional, the right rug is one of these:</p>
<ul>
<li><strong>200 × 300 cm (about 6 ft 7 in × 9 ft 10 in):</strong> for compact and mid-sized sectionals, laid with its long side running along the short arm of the sofa.</li>
<li><strong>240 × 300 cm (8 × 10 ft):</strong> the most useful all-rounder for a larger L-shaped sofa.</li>
<li><strong>270 × 360 cm (9 × 12 ft):</strong> the largest rug that sensibly fits this room, for a &ldquo;room-sized&rdquo; look where the whole seating group sits on the rug.</li>
</ul>
<p>A 160 × 230 cm (about 5 × 8 ft) rug is almost always too small for a sectional in a room this size. It usually ends before the coffee table does, which is the clearest sign a rug is undersized.</p>

<h2 id="the-three-rules">The three rules behind every rug size</h2>
<h3>1. Leave a border of floor around the rug</h3>
<p>Aim to leave roughly 30&ndash;45 cm (12&ndash;18 in) of bare floor between the rug and the walls. This frames the rug and stops it looking like fitted carpet. In a 366 × 427 cm room, that gives a maximum rug size of:</p>
<ul>
<li><strong>Width:</strong> 366 &minus; (2 × 30) = 306 cm at most, and 366 &minus; (2 × 45) = 276 cm for a more generous border.</li>
<li><strong>Length:</strong> 427 &minus; (2 × 30) = 367 cm at most, and 427 &minus; (2 × 45) = 337 cm for a more generous border.</li>
</ul>
<p>A 270 × 360 cm rug centred in the room leaves 48 cm on the long sides and about 33 cm on the short sides, so it sits right at the edge of the rule. Anything bigger starts to look wall-to-wall.</p>

<h3>2. Front legs on the rug</h3>
<p>With a sectional, the rug should slide under the front legs of both arms of the L, by roughly 15&ndash;20 cm (6&ndash;8 in). This links the sofa and the rug into one seating zone. The back legs can sit on the bare floor; that is normal and looks intentional.</p>

<h3>3. The rug should reach the end of the long arm</h3>
<p>Ideally the rug finishes level with the open end of the long arm, or up to about 30 cm (12 in) beyond it. A rug that stops well inside the arm looks skimpy; one that runs far past it starts to compete with the sofa.</p>

<h2 id="the-formula">A simple formula for L-shaped sofas</h2>
<p>You need three measurements: the length of the long arm (L), the length of the short arm (S) and the seat depth (D), measured from the back of the sofa to the front edge of the seat cushion.</p>
<ul>
<li><strong>Rug dimension along the long arm:</strong> L &minus; D + 20 cm, plus up to 30 cm extra if you want the rug to run past the arm&rsquo;s end.</li>
<li><strong>Rug dimension along the short arm:</strong> at least S &minus; D + 20 cm. In practice you go further than this so the rug carries on past the end of the short arm and holds the coffee table, finishing 30&ndash;45 cm short of the opposite wall or media unit.</li>
</ul>
<p>The &ldquo;+ 20 cm&rdquo; is the tuck under the seats. The &ldquo;&minus; D&rdquo; accounts for the corner of the L, which the rug slides beneath rather than wraps around.</p>

<h2 id="worked-examples">Worked examples in a 12 × 14 room</h2>
<p>All three examples use the same layout: the long arm of the sectional runs along one 366 cm (12 ft) wall, facing the TV on the opposite wall, with the short arm along a 427 cm (14 ft) wall. The sofa sits about 10 cm off both walls so it does not rub the paint.</p>

<h3>Example A: compact sectional, 270 × 200 cm</h3>
<p>Long arm 270 cm (about 8 ft 10 in), short arm 200 cm (about 6 ft 7 in), seat depth 95 cm.</p>
<ul>
<li><strong>Along the long arm:</strong> 270 &minus; 95 + 20 = 195 cm, up to 225 cm.</li>
<li><strong>Along the short arm:</strong> at least 200 &minus; 95 + 20 = 125 cm, and realistically as long as the room allows.</li>
<li><strong>Best fit:</strong> a 200 × 300 cm rug, with 200 cm running along the long arm and 300 cm running along the short arm and on into the room.</li>
<li><strong>Check:</strong> the rug starts 85 cm from the side wall (10 cm gap + 95 cm seat &minus; 20 cm tuck) and ends 5 cm past the long arm. Along the room it runs from 85 cm to 385 cm, leaving 42 cm of floor in front of the TV wall. Both borders fall inside the 30&ndash;45 cm range.</li>
</ul>

<h3>Example B: large sectional, 300 × 240 cm</h3>
<p>Long arm 300 cm (about 9 ft 10 in), short arm 240 cm (about 7 ft 10 in), seat depth 100 cm.</p>
<ul>
<li><strong>Along the long arm:</strong> 300 &minus; 100 + 20 = 220 cm, up to 250 cm.</li>
<li><strong>Along the short arm:</strong> at least 240 &minus; 100 + 20 = 160 cm.</li>
<li><strong>Best fit:</strong> a 240 × 300 cm (8 × 10 ft) rug, 240 cm along the long arm.</li>
<li><strong>Check:</strong> the rug starts 90 cm from the side wall and ends 20 cm past the long arm, leaving 36 cm of floor to the far wall. Along the room it runs from 90 cm to 390 cm, leaving 37 cm before the TV wall. A wall-mounted TV or a slim media unit with its front legs just touching the rug both work here.</li>
</ul>

<h3>Example C: room-sized rug with a 320 × 220 cm sectional</h3>
<p>If you prefer the whole seating group on the rug, including an accent chair, use the largest rug the room allows: 270 × 360 cm (9 × 12 ft), centred in the room.</p>
<ul>
