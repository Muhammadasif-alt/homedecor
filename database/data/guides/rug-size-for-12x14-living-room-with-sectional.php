<p>For a 12 × 14 living room with a sectional, start with 240 × 300 cm, check the formula against your own sofa, and confirm it with tape on the floor. Size down to 200 × 300 cm for a compact L; size up to 270 × 360 cm if you want the whole seating group on the rug.</p>
