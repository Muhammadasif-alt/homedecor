<h2 id="extension-leads">Extension leads and chargers</h2>
<p>Student rooms rarely have enough sockets, which tempts people into risky habits.</p>
<ul>
<li><strong>Never daisy-chain extension leads</strong> by plugging one into another.</li>
<li>Use a single fused extension lead, ideally a surge-protected bar, rather than block adaptors.</li>
<li>Don’t overload sockets: check the lead’s rating and avoid running several high-power items from one lead.</li>
<li>Keep leads uncoiled, visible and out of walkways; never run them under rugs or bedding where damage goes unnoticed.</li>
<li>Use the charger that came with your device or a reputable replacement, and don’t charge phones or laptops under pillows or on the bed.</li>
<li>Replace anything with a frayed cable, scorch marks or a warm plug.</li>
</ul>

<h2 id="exits-and-detectors">Keep exits and detectors clear</h2>
<ul>
<li><strong>Never cover, disconnect or tamper with smoke detectors or heat detectors</strong>, not even with a shower cap or bag “just for a minute”. It is dangerous and is often treated as a serious disciplinary matter.</li>
<li>Keep a generous clear space around detectors and sprinkler heads, don’t stack anything tall beneath them and never hang anything from them. Your halls’ guidance may specify a minimum clearance.</li>
<li>Don’t prop open fire doors, including your own room door if it is a fire door.</li>
<li>Keep the route from your bed to the door clear of boxes, laundry and furniture. Imagine finding your way out in the dark.</li>
<li>Know your building’s escape route and assembly point; walk it once in your first week.</li>
</ul>

