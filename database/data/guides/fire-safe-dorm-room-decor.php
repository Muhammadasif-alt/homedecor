<p>A student room is often small, shared with a lot of electrical equipment and surrounded by dozens of other rooms. That is why halls of residence (dorms, in American terms) usually have strict fire safety rules, and why decorating one takes a little more thought than decorating a flat. The good news is that the safest choices are also some of the easiest to style: soft LED light, washable textiles, freestanding storage and pieces you can take with you when you move out.</p>
<p>This guide covers what to check before you buy anything, which materials and products to look for, and how to make the room feel personal without putting yourself, your neighbours or your deposit at risk.</p>

<h2 id="check-the-rules">Start with your halls’ rules</h2>
<p>Before you order a single cushion, read your accommodation agreement and the halls’ fire safety guidance. Rules vary between providers, but these are commonly restricted or banned:</p>
<ul>
<li><strong>Candles, incense, oil burners and reed diffusers</strong> with a naked flame or heat source.</li>
<li><strong>Mains-powered string lights</strong> or decorative lighting, sometimes allowed only if battery-powered or certified.</li>
<li><strong>Fabric hung from ceilings</strong>, including tapestries, canopies and draped nets, because they spread fire quickly and can block sprinklers or detectors.</li>
<li><strong>Adhesives on walls</strong>, such as sticky putty, tape and adhesive hooks, which can damage paint and lead to deductions from your deposit.</li>
<li><strong>Personal appliances</strong> like kettles, toasters, heaters and rice cookers in bedrooms.</li>
<li><strong>Extra furniture</strong>, especially upholstered pieces brought from home.</li>
</ul>
<p>If something is unclear, ask the accommodation office in writing and keep the reply. It is much easier than arguing about a fine or a damaged wall at the end of the year.</p>

<h2 id="flame-retardant-fabrics">Choose flame-retardant fabrics</h2>
<p>Textiles do most of the work of making a room feel cosy, so it is worth choosing them carefully.</p>
<ul>
<li><strong>Read the labels:</strong> look for curtains, throws and upholstered items labelled as flame-retardant or meeting the relevant fire safety standard where you live. In the UK, new upholstered furniture should carry a permanent fire safety label.</li>
<li><strong>Bring furniture only if allowed:</strong> many halls ban upholstered furniture from home precisely because its fire safety status is unknown. A beanbag or second-hand armchair may not be permitted.</li>
<li><strong>Prefer natural, tightly woven fibres:</strong> wool throws and heavy cotton generally burn less readily than loose, fluffy synthetics, though no fabric is fireproof.</li>
<li><strong>Keep fabrics away from heat:</strong> never drape a scarf or throw over a lamp shade, and keep bedding and curtains clear of chargers, laptops and any heater supplied by the halls.</li>
</ul>

<h2 id="lighting-safely">Lighting that is safe and cosy</h2>
<p>Overhead lighting in halls is often harsh. Softer lighting changes the mood of the room more than almost anything else, and it can be done safely.</p>
<ul>
<li><strong>LED battery candles:</strong> a cluster of flameless candles of different heights on a tray gives the glow of real candles with no flame. Many have timers, so they switch off automatically.</li>
<li><strong>Battery or USB string lights:</strong> if mains string lights are banned, battery or USB-powered LED versions are often allowed. Check first, and hang them with removable fixings approved by your halls, never across a ceiling or over a door frame.</li>
<li><strong>Certified plug-in lights:</strong> if you bring a desk or bedside lamp, buy it new from a reputable retailer, look for safety markings (such as UKCA or CE in the UK), and use LED bulbs, which run much cooler than old-style bulbs.</li>
<li><strong>Clip-on lamps:</strong> a clip-on LED reading lamp on a bedhead or shelf saves desk space. Make sure the clip is firm and the head is not touching fabric.</li>
<li><strong>Switch off:</strong> turn decorative lights off when you leave the room or go to sleep.</li>
</ul>
