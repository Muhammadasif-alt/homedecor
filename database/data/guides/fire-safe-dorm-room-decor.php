<ul>
<li>Pick a simple palette of two or three colours and repeat it across bedding, a throw, cushions and a rug.</li>
<li>Layer a flat-woven rug over a hard floor for warmth; it is low-profile, easy to wash and less of a trip hazard than a deep shag.</li>
<li>Swap the bedding seasonally: linen or cotton in summer, a wool throw in winter.</li>
</ul>
<h3 id="plants-and-scent">Plants and scent without flames</h3>
