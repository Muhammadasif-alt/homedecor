<h2 id="art-and-mirrors">Art and mirrors without holes</h2>
<ul>
<li><strong>Lean, don’t hang.</strong> Art and mirrors leaning on sideboards, picture ledges or the floor can be rearranged freely in every new home.</li>
<li><strong>Use standard frame sizes</strong> so prints can be swapped and frames re-used.</li>
<li><strong>Build a flexible collection</strong> of pieces in different sizes rather than one very large artwork that only fits a certain wall.</li>
<li><strong>Follow weight ratings</strong> on removable strips and test them on a hidden spot first; heavier pieces are better leaning. Our guide to <a href="/blog/heavy-mirror-and-shelving-rental-no-drilling">heavy mirrors and shelving without drilling</a> covers this in detail.</li>
</ul>

<h2 id="soft-furnishings">Soft furnishings and accessories</h2>
<p>Cushions, throws, baskets and plants travel easily and do a lot of the work of making a space feel personal. Keep to a loose colour palette, perhaps two main colours and one accent, so pieces you bought for one flat still work together in the next. Baskets and lidded boxes double as packing containers on moving day.</p>

<h2 id="packing-tips">Packing tips so pieces arrive intact</h2>
<ul>
<li><strong>Photograph furniture before you take it apart</strong>, and keep the assembly instructions in a labelled folder.</li>
<li><strong>Bag and label fixings</strong>, taping each bag to the piece it belongs to.</li>
<li><strong>Wrap legs and corners</strong> with corner protectors or cardboard; remove legs where possible.</li>
<li><strong>Roll rugs</strong> pile-side in and wrap them in a breathable cover; avoid folding them, which can leave creases.</li>
<li><strong>Pack mirrors and framed art upright</strong>, never flat, in mirror boxes or between sheets of cardboard, with extra protection on the corners.</li>
<li><strong>Use curtains and throws as padding</strong> around lamps and ceramics, but pack lampshades separately so they are not crushed.</li>
<li><strong>Measure the new home first</strong>, including doorways, stairs and lifts, so you know what will fit and where it will go.</li>
</ul>
