<p>If you rent, your furniture will probably see several homes. Each move brings a new floor plan, different window sizes, unfamiliar wall rules and, often, a narrow staircase. The pieces that survive are not always the most expensive ones; they are the ones that adapt. Choosing decor that travels well between apartments saves money, reduces waste and means each new place feels like home sooner.</p>
<p>This guide explains what to look for, category by category, and how to pack it so it arrives in one piece.</p>

<h2 id="the-principles">The principles: adaptable, standard, demountable</h2>
<p>Before buying anything for a rental, ask three questions:</p>
<ul>
<li><strong>Will it work in a different room?</strong> A sideboard that can serve as a TV unit, a hallway console or bedroom storage is worth more to a renter than a piece that only fits one spot.</li>
<li><strong>Is it a standard size?</strong> Standard mattress, curtain and frame sizes are easy to replace and re-use.</li>
<li><strong>Can it come apart?</strong> Removable legs, bolt-together frames and flat-pack-able designs get through doorways and into lifts that a solid piece will not.</li>
</ul>

<h2 id="furniture">Furniture that adapts</h2>
<h3>Modular and demountable pieces</h3>
<ul>
<li><strong>Modular sofas</strong> can be reconfigured from a corner sofa to two separate seats or a straight run as rooms change. Check that the sections lock together securely.</li>
<li><strong>Sofas with removable legs and arms</strong> fit through tighter doorways. Measure door widths, stair turns and lift dimensions before moving day.</li>
<li><strong>Bolt-together beds and shelving</strong> survive repeated assembly better than furniture held together with cam locks in chipboard, which can loosen each time.</li>
<li><strong>Extending or drop-leaf dining tables</strong> suit both a studio and a larger flat.</li>
</ul>
<h3>Sizes that travel</h3>
<ul>
<li>Keep large pieces moderate in scale. A sofa of around 180–210 cm (71–83 in) fits most living rooms; very deep or very long sofas limit your choice of next home.</li>
<li>Choose a standard double or king-size bed so mattresses, bedding and frames are easy to replace.</li>
<li>Low, wide storage is easier to move and more stable than tall, narrow units, and can often double as a bench or display surface.</li>
<li>Nesting tables, stools and folding chairs flex from extra seating to bedside tables.</li>
</ul>
<p>For more on making a compact plan work, see <a href="/blog/how-to-arrange-furniture-in-a-small-living-room">how to arrange furniture in a small living room</a>.</p>

<h2 id="rugs-and-curtains">Rugs and curtains that adapt</h2>
<h3>Rugs</h3>
<ul>
<li><strong>Mid-sized rugs</strong> of around 160 × 230 cm (5 × 8 ft) or 200 × 300 cm (6½ × 10 ft) suit most living rooms and bedrooms. Very large rugs may not fit the next home; very small ones can look lost.</li>
<li><strong>Layering</strong> lets a smaller favourite rug sit on top of a plain, larger one if the next room is bigger.</li>
<li><strong>Flatweaves and washable rugs</strong> roll tightly for moving and are easier to clean between tenancies.</li>
<li>Use a non-slip underlay sized to the rug; it travels with it.</li>
</ul>
<h3>Curtains</h3>
<p>Windows change with every move, so curtains need to flex:</p>
<ul>
<li>Buy longer than you need. Floor-length curtains can be hemmed up, clipped with ring hooks or tied back; short curtains cannot be lengthened easily.</li>
<li>Choose generous widths, around 1.5–2 times the window width, so curtains still cover a wider window in the next flat.</li>
<li>Header styles that work with both poles and tracks, such as tab-top with removable hooks or pencil pleat, give you more options.</li>
<li>Keep a telescopic pole and a tension rod; between them they cover many windows. For tricky windows, read our guide to <a href="/blog/curtains-for-awkward-and-bay-windows-renters">curtains for awkward and bay windows</a>.</li>
</ul>

<h2 id="lighting">Lighting that plugs in</h2>
<p>Ceiling lights stay with the property, but plug-in lighting moves with you, and it does most of the work of making a room feel warm.</p>
<ul>
<li><strong>Floor lamps</strong> light reading corners and fill dark areas without wiring.</li>
<li><strong>Table lamps</strong> work on sideboards, desks and bedside tables in any layout.</li>
<li><strong>Plug-in wall lights</strong> with a neat cable run give the look of wall lights without an electrician; check the cable can be routed safely and not trailed across walkways.</li>
<li><strong>Lightweight shades</strong>, such as paper lanterns, are inexpensive and can fold or nest for moving.</li>
<li><strong>Warm white bulbs</strong> of similar colour temperature across all lamps make any rental feel more cohesive.</li>
</ul>
