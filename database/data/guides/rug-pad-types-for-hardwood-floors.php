<p>A rug pad (in the UK usually called a rug underlay) is the least glamorous thing in a living room and one of the most useful. On a hardwood floor it stops the rug sliding, adds comfort underfoot, reduces wear on the rug&rsquo;s backing and helps protect the floor&rsquo;s finish from grit. But not every pad is kind to wood. This guide compares the main rug pad types for hardwood, explains which thickness to choose, and covers the practical details: cutting to size, rugs under furniture and underfloor heating.</p>

<h2 id="why-hardwood-needs-the-right-pad">Why hardwood needs the right pad</h2>
<p>Wooden floors are finished with lacquer, oil, hardwax oil or similar coatings. A rug pad sits on that finish for months or years, pressed down by furniture and feet. The wrong material can mark it, stick to it or trap moisture against it. The right one grips the floor gently, lets the floor breathe and lifts away cleanly when you move the rug.</p>
<p>Engineered wood, solid wood and many laminates share these concerns, so the advice below applies broadly. Always check your floor manufacturer&rsquo;s guidance first; some name specific pad materials to use or avoid.</p>

<h2 id="the-main-types">The main rug pad types compared</h2>

<h3>1. Felt pads</h3>
<p>Dense felt, often made from recycled fibres, is the cushioning choice.</p>
<ul>
<li><strong>Good for:</strong> large rugs held in place by furniture, such as a 240 × 300 cm (8 × 10 ft) rug under a sofa and coffee table.</li>
<li><strong>Strengths:</strong> soft underfoot, adds a feeling of quality to thinner rugs, dampens footstep noise, and is generally gentle on wood.</li>
<li><strong>Limits:</strong> felt alone offers little grip. On an open floor, a rug on a felt-only pad can still slide or ruck up.</li>
</ul>

<h3>2. Felt and natural rubber pads</h3>
<p>A layer of felt bonded to a thin layer of natural rubber. This is the best all-rounder for most living rooms on hardwood.</p>
<ul>
<li><strong>Good for:</strong> most rugs in living rooms, bedrooms and dining rooms, including medium rugs that are not fully pinned down by furniture.</li>
<li><strong>Strengths:</strong> the felt gives cushioning, the rubber side faces the floor and grips it.</li>
<li><strong>How to lay it:</strong> rubber side down against the floor, felt side up against the rug, unless the maker says otherwise.</li>
</ul>

<h3>3. Natural rubber pads</h3>
<p>Thin, solid or waffle-textured sheets of natural rubber.</p>
<ul>
<li><strong>Good for:</strong> runners in hallways, small rugs by the sofa or bed, and rugs in front of doors where height matters.</li>
<li><strong>Strengths:</strong> excellent grip with very little added height, so doors still clear the rug.</li>
<li><strong>Limits:</strong> little cushioning. People with a latex allergy should check the product details, as natural rubber is derived from latex.</li>
</ul>

<h3>4. PVC and plastic pads</h3>
<p>The open-mesh pads often sold on a roll are usually PVC or a similar synthetic.</p>
<ul>
<li><strong>Why they are common:</strong> they are thin, easy to cut and widely available.</li>
<li><strong>The caution:</strong> some PVC and plastic pads can react with certain floor finishes over time, leaving a pattern, a sticky residue or discoloured patches, particularly in warm rooms or on underfloor heating. They can also break down and crumble with age.</li>
<li><strong>Our view:</strong> on a good wooden floor, choose felt, felt and natural rubber, or natural rubber instead. If you do use a synthetic pad, check that both the pad maker and your floor manufacturer say it is suitable for your finish.</li>
</ul>

<h3>Other options you may see</h3>
<ul>
<li><strong>Memory foam pads:</strong> very soft, but usually best saved for low-traffic spots and paired with a grippy base layer.</li>
<li><strong>Rug grippers and corner tapes:</strong> handy for lifting corners, but adhesive types can mark wood, so test on a hidden spot and check the floor guidance first.</li>
</ul>

<h2 id="choosing-thickness">Choosing the right thickness</h2>
<p>Thickness is a balance between comfort, grip and door clearance.</p>
<ul>
<li><strong>About 3 mm (1/8 in):</strong> runners, small rugs, rugs near doors and flat-weave rugs where you just need grip. Natural rubber or a thin felt and rubber pad.</li>
<li><strong>About 6 mm (1/4 in):</strong> the everyday choice for living room and bedroom rugs. Enough cushioning to make a flat-weave feel more substantial without creating a trip edge.</li>
<li><strong>About 10 mm (3/8 in) or more:</strong> large rugs in seating areas where you want a plush feel underfoot and nothing needs to pass over the rug.</li>
</ul>
<p>As a rule, thick, deep-pile rugs need a thinner pad, while thin flat-weaves benefit from a thicker one. Before buying, measure the gap under any door that will swing over the rug and make sure the combined height of rug and pad clears it comfortably.</p>

<h2 id="cutting-to-size">Cutting the pad to the right size</h2>
<p>A rug pad should be slightly smaller than the rug so it is hidden and the rug edges can lie flat against the floor. Cut it about 2.5 cm (1 in) in from the rug edge on each side.</p>
<ul>
<li><strong>The formula:</strong> pad size = rug size minus 5 cm (2 in) in each direction.</li>
<li><strong>Example:</strong> a 200 × 300 cm rug needs a pad of 195 × 295 cm. A 240 × 300 cm rug needs 235 × 295 cm.</li>
<li><strong>Round and odd-shaped rugs:</strong> lay the pad flat, place the rug on top, trace around it with chalk, then draw a second line 2.5 cm inside and cut along that.</li>
</ul>
<p>Most felt and rubber pads cut cleanly with sharp household scissors or a utility knife on a cutting board. Cut slowly and keep the edge straight, as a ragged pad edge can show through thin rugs.</p>

<blockquote><p><strong>Tip:</strong> Lay the pad, then unroll the rug onto it from one end rather than dropping the rug on top. It is much easier to keep everything square, and you will not have to drag the rug across the pad.</p></blockquote>

<h2 id="underfloor-heating">Rug pads and underfloor heating</h2>
<p>Underfloor heating and rugs can work together, but every layer you add insulates the floor and slows heat getting into the room.</p>
<ul>
<li><strong>Check the system guidance:</strong> underfloor heating manufacturers often give a maximum combined tog value (thermal resistance) for floor coverings. In the UK, a combined figure of around 2.5 tog is commonly quoted, but follow the guidance for your own system.</li>
<li><strong>Choose thinner pads:</strong> a thin felt and natural rubber or natural rubber pad adds far less insulation than a thick felt one.</li>
<li><strong>Look for suitability:</strong> some pads are labelled as suitable for underfloor heating; others are not. Avoid PVC pads here unless the maker explicitly approves them, as warmth can speed up any reaction with the finish.</li>
<li><strong>Watch for heat build-up:</strong> very thick rug and pad combinations can trap heat. If in doubt, ask your heating installer.</li>
</ul>

<h2 id="care-and-protection">Care and floor protection</h2>
<ul>
<li><strong>New floors:</strong> freshly finished or oiled floors need time to cure before anything is laid on them. Check the finish manufacturer&rsquo;s cure time, which can be several weeks.</li>
<li><strong>Lift and clean:</strong> every few months, lift the rug and pad, vacuum the floor and the pad, and let everything air before relaying. Grit trapped underneath is what scratches the finish.</li>
<li><strong>Rotate the rug:</strong> wood can change colour with sunlight. Turning the rug occasionally helps the floor age more evenly and spreads wear on the rug.</li>
<li><strong>Spills:</strong> if liquid soaks through, lift the rug and let the pad and floor dry fully, as moisture trapped against wood can damage it.</li>
<li><strong>Replace tired pads:</strong> if a pad has hardened, crumbled or lost its grip, replace it.</li>
</ul>

<h2 id="quick-guide">Quick guide: which pad for which rug</h2>
<ul>
<li><strong>Large living room rug under the sofa:</strong> felt and natural rubber, about 6 mm, or felt alone if furniture pins every side.</li>
<li><strong>Medium rug in an open area:</strong> felt and natural rubber, about 6 mm.</li>
<li><strong>Hallway runner or rug by a door:</strong> natural rubber, about 3 mm.</li>
<li><strong>Thin flat-weave you want to feel plusher:</strong> felt and natural rubber, 6&ndash;10 mm.</li>
<li><strong>Floor with underfloor heating:</strong> the thinnest pad that does the job, labelled as suitable.</li>
</ul>

<h2 id="final-thoughts">Getting it right</h2>
<p>For most hardwood floors, a felt and natural rubber pad around 6 mm thick, cut 2.5 cm smaller than the rug on each side, is the safe default. Go thinner for runners, doorways and underfloor heating, and be wary of PVC pads on a floor you care about.</p>
